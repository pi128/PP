var rcon = [...]byte{0x00, 0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36}

func xtime(x byte) byte { // multiply by 0x02 in GF(2^8)
	if x&0x80 != 0 {
		return (x << 1) ^ 0x1b
	}
	return x << 1
}

func gmul(a, b byte) byte {
	var p byte
	for i := 0; i < 8; i++ {
		if b&1 != 0 {
			p ^= a
		}
		hi := a & 0x80
		a <<= 1
		if hi != 0 {
			a ^= 0x1b
		}
		b >>= 1
	}
	return p
}

type AES struct {
	roundKeys [Nr + 1][BlockSize]byte
}

func NewAES128(key []byte) (*AES, error) {
	if len(key) != 16 {
		return nil, errors.New("AES-128 requires a 16-byte key")
	}
	a := &AES{}
	expandKey128(a, key)
	return a, nil
}

func expandKey128(a *AES, key []byte) {

	var w [Nb * (Nr + 1)][4]byte // [44][4]
	for i := 0; i < Nk; i++ {
		copy(w[i][:], key[4*i:4*i+4])
	}
	rotWord := func(x [4]byte) [4]byte { return [4]byte{x[1], x[2], x[3], x[0]} }
	subWord := func(x [4]byte) [4]byte {
		return [4]byte{sbox[x[0]], sbox[x[1]], sbox[x[2]], sbox[x[3]]}
	}
	for i := Nk; i < Nb*(Nr+1); i++ {
		t := w[i-1]
		if i%Nk == 0 {
			t = subWord(rotWord(t))
			t[0] ^= rcon[i/Nk]
		}
		for j := 0; j < 4; j++ {
			w[i][j] = w[i-Nk][j] ^ t[j]
		}
	}
	// Pack words into 11 round keys of 16 bytes
	for r := 0; r <= Nr; r++ {
		for c := 0; c < Nb; c++ {
			copy(a.roundKeys[r][4*c:], w[r*Nb+c][:])
		}
	}
}

func (a *AES) addRoundKey(state []byte, r int) {
	for i := 0; i < 16; i++ {
		state[i] ^= a.roundKeys[r][i]
	}
}
func (a *AES) subBytes(state []byte) {
	for i := 0; i < 16; i++ {
		state[i] = sbox[state[i]]
	}
}
func (a *AES) invSubBytes(state []byte) {
	for i := 0; i < 16; i++ {
		state[i] = invSbox[state[i]]
	}
}
func (a *AES) shiftRows(state []byte) {
	for r := 0; r < 4; r++ {
		tmp := [4]byte{}
		for c := 0; c < 4; c++ {
			tmp[c] = state[4*((c+r)&3)+r]
		}
		for c := 0; c < 4; c++ {
			state[4*c+r] = tmp[c]
		}
	}
}
func (a *AES) invShiftRows(state []byte) {
	for r := 0; r < 4; r++ {
		tmp := [4]byte{}
		for c := 0; c < 4; c++ {
			tmp[c] = state[4*((c-r+4)&3)+r]
		}
		for c := 0; c < 4; c++ {
			state[4*c+r] = tmp[c]
		}
	}
}
func (a *AES) mixColumns(state []byte) {
	mat := [4][4]byte{
		{0x02, 0x03, 0x01, 0x01},
		{0x01, 0x02, 0x03, 0x01},
		{0x01, 0x01, 0x02, 0x03},
		{0x03, 0x01, 0x01, 0x02},
	}
	for c := 0; c < 4; c++ {
		col := [4]byte{state[4*c+0], state[4*c+1], state[4*c+2], state[4*c+3]}
		for r := 0; r < 4; r++ {
			var v byte
			for k := 0; k < 4; k++ {
				switch mat[r][k] {
				case 0x01:
					v ^= col[k]
				case 0x02:
					v ^= xtime(col[k])
				case 0x03:
					v ^= xtime(col[k]) ^ col[k]
				}
			}
			state[4*c+r] = v
		}
	}
}
func (a *AES) invMixColumns(state []byte) {
	mat := [4][4]byte{
		{0x0e, 0x0b, 0x0d, 0x09},
		{0x09, 0x0e, 0x0b, 0x0d},
		{0x0d, 0x09, 0x0e, 0x0b},
		{0x0b, 0x0d, 0x09, 0x0e},
	}
	for c := 0; c < 4; c++ {
		col := [4]byte{state[4*c+0], state[4*c+1], state[4*c+2], state[4*c+3]}
		for r := 0; r < 4; r++ {
			var v byte
			for k := 0; k < 4; k++ {
				v ^= gmul(mat[r][k], col[k])
			}
			state[4*c+r] = v
		}
	}
}

func (a *AES) EncryptBlock(dst, src []byte) {
	if len(src) < 16 || len(dst) < 16 {
		panic("EncryptBlock needs 16 bytes")
	}
	state := make([]byte, 16)
	copy(state, src[:16])

	a.addRoundKey(state, 0)
	for r := 1; r < Nr; r++ {
		a.subBytes(state)
		a.shiftRows(state)
		a.mixColumns(state)
		a.addRoundKey(state, r)
	}
	a.subBytes(state)
	a.shiftRows(state)
	a.addRoundKey(state, Nr)

	copy(dst, state)
}

func (a *AES) DecryptBlock(dst, src []byte) {
	if len(src) < 16 || len(dst) < 16 {
		panic("DecryptBlock needs 16 bytes")
	}
	state := make([]byte, 16)
	copy(state, src[:16])

	a.addRoundKey(state, Nr)
	for r := Nr - 1; r >= 1; r-- {
		a.invShiftRows(state)
		a.invSubBytes(state)
		a.addRoundKey(state, r)
		a.invMixColumns(state)
	}
	a.invShiftRows(state)
	a.invSubBytes(state)
	a.addRoundKey(state, 0)

	copy(dst, state)
}

func pkcs7Pad(b []byte) []byte {
	p := BlockSize - (len(b) % BlockSize)
	return append(b, bytes.Repeat([]byte{byte(p)}, p)...)
}
func pkcs7Unpad(b []byte) ([]byte, error) {
	if len(b) == 0 || len(b)%BlockSize != 0 {
		return nil, errors.New("bad padding len")
	}
	p := int(b[len(b)-1])
	if p == 0 || p > BlockSize {
		return nil, errors.New("bad padding value")
	}
	for i := 0; i < p; i++ {
		if b[len(b)-1-i] != byte(p) {
			return nil, errors.New("bad padding bytes")
		}
	}
	return b[:len(b)-p], nil
}

func (a *AES) EncryptECB(plain []byte) []byte {
	plain = pkcs7Pad(plain)
	out := make([]byte, len(plain))
	for i := 0; i < len(plain); i += 16 {
		a.EncryptBlock(out[i:i+16], plain[i:i+16])
	}
	return out
}
func (a *AES) DecryptECB(ct []byte) ([]byte, error) {
	if len(ct)%16 != 0 {
		return nil, errors.New("ciphertext not multiple of 16")
	}
	out := make([]byte, len(ct))
	for i := 0; i < len(ct); i += 16 {
		a.DecryptBlock(out[i:i+16], ct[i:i+16])
	}
	return pkcs7Unpad(out)
}

func kat128(keyHex, ptHex, ctHex string) bool {
	key, _ := hex.DecodeString(keyHex)
	pt, _ := hex.DecodeString(ptHex)
	want, _ := hex.DecodeString(ctHex)

	c, err := NewAES128(key)
	if err != nil {
		panic(err)
	}
	out := make([]byte, 16)
	c.EncryptBlock(out, pt)
	ok := bytes.Equal(out, want)

	dec := make([]byte, 16)
	c.DecryptBlock(dec, out)
	ok = ok && bytes.Equal(dec, pt)
	return ok
}

